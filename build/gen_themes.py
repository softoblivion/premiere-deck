"""Render the two project themes of `src/premiere_deck/ui/themes.json` into the generated CSS.

docs/ARCHITECTURE.md 3, docs/HOST_UI.md 7, docs/PANEL.md 3. Outputs:

- `src/premiere_deck/ui/vendor/liquid_ui/css/themes.css` (the whole file): one rule per theme with every token,
  `:root, :root[data-theme="black"], [data-theme-scope="black"]` for the default theme and
  `:root[data-theme="<name>"], [data-theme-scope="<name>"]` for the others. `data-theme-scope` lets a subtree (the
  mini previews of the settings theme cards) carry another theme's tokens.
- `src/premiere_deck/panel/css/panel.css`: the block between `BEGIN_MARK` and `END_MARK` (the text font face, the
  font tokens and one rule per theme under `:root[data-theme=...]`, the same token names and values as the host).
  The rest of panel.css is left as it is.

themes.json, per theme: `name`, `label`, `scheme` (dark | light), `hue`, `accent`, `derived` (what `derive()` of
the kit copy's js/theme.js returns for hue and accent; kept in the file so a reader sees the whole set), `overrides`
(derived tokens this theme replaces) and `tokens` (every other token). The written set is `derived` with
`overrides` applied, then `tokens`.

Usage:
    python build/gen_themes.py            write both outputs
    python build/gen_themes.py --check    write nothing; exit 1 when an output differs from what would be written

Standard library only (run by build/build.ps1 before the bundle and by tests/test_themes.py).
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEMES_JSON = ROOT / "src" / "premiere_deck" / "ui" / "themes.json"
KIT_THEMES_CSS = ROOT / "src" / "premiere_deck" / "ui" / "vendor" / "liquid_ui" / "css" / "themes.css"
PANEL_CSS = ROOT / "src" / "premiere_deck" / "panel" / "css" / "panel.css"

BEGIN_MARK = "/* BEGIN generated by build/gen_themes.py from ui/themes.json */"
END_MARK = "/* END generated */"

SCHEMES = ("dark", "light")
MIN_CONTRAST = 4.5
# Text inks held to MIN_CONTRAST over the glass and the sheet tint above every scene point (docs/HOST_UI.md 7).
# --ink-4 is for disabled and decorative marks only.
TEXT_INKS = ("--ink-1", "--ink-2", "--ink-3", "--accent-ink", "--ok-ink", "--warn-ink", "--error-ink", "--rose-ink",
             "--info-ink")


# ---------------------------------------------------------------------------------------------------------------------
# derive(): a port of the kit copy's js/theme.js (same arithmetic and number formatting as the JavaScript)

def _js_round(value: float) -> int:
    return math.floor(value + 0.5)


def _rgb(hex_text: str) -> list[int]:
    n = int(hex_text[1:], 16)
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255]


def _hex(values) -> str:
    return "#" + "".join(f"{max(0, min(255, _js_round(v))):02x}" for v in values)


def _mix(a, b, k: float) -> list[float]:
    return [v + (b[i] - v) * k for i, v in enumerate(a)]


def _num(value: float) -> str:
    text = repr(float(value))
    return text[:-2] if text.endswith(".0") else text


def _rgba(values, alpha: float) -> str:
    return f"rgba({', '.join(str(_js_round(v)) for v in values)}, {_num(alpha)})"


def derive(hue: str, accent: str) -> dict[str, str]:
    """Identity and scene tokens for a hue / accent pair (js/theme.js derive())."""
    h = _rgb(hue)
    a = _rgb(accent)
    black = [0, 0, 0]
    white = [255, 255, 255]
    light = _mix(a, white, 0.22)
    deep = _mix(a, h, 0.42)
    return {
        "--accent": accent,
        "--accent-2": _hex(deep),
        "--accent-ink": _hex(_mix(a, white, 0.56)),
        "--accent-grad": f"linear-gradient(135deg, {_hex(light)} 0%, {accent} 48%, {_hex(deep)} 100%)",
        "--accent-grad-a": f"linear-gradient(135deg, {_rgba(light, 0.74)} 0%, {_rgba(a, 0.74)} 48%, {_rgba(deep, 0.78)} 100%)",
        "--btn-glow": _rgba(a, 0.55),
        "--focus-ring": _rgba(_mix(a, white, 0.45), 0.95),
        "--glyph-glow": _rgba(_mix(h, white, 0.2), 0.55),
        "--bg-top": _hex(_mix(h, black, 0.95)),
        "--bg-mid": _hex(_mix(h, black, 0.86)),
        "--bg-bottom": _hex(_mix(h, black, 0.74)),
        "--scene-hue": hue,
        "--scene-accent": accent,
        "--scene-line": _hex(_mix(h, white, 0.74)),
        "--tint-regular": _rgba(_mix(h, black, 0.82), 0.3),
        "--tint-sheet": _rgba(_mix(h, black, 0.88), 0.52),
        "--well": _rgba(_mix(h, black, 0.92), 0.4),
    }


# ---------------------------------------------------------------------------------------------------------------------
# The theme file

def load(path: Path = THEMES_JSON) -> dict:
    return json.loads(path.read_text("utf-8"))


def theme_tokens(theme: dict) -> dict[str, str]:
    """Every token of one theme, in the written order."""
    out = dict(theme["derived"])
    out.update(theme.get("overrides", {}))
    out.update(theme["tokens"])
    return out


def problems(data: dict) -> list[str]:
    """What is wrong with the theme file (empty when it is consistent)."""
    found: list[str] = []
    themes = data.get("themes")
    if not isinstance(themes, list) or not themes:
        return ["no themes"]
    names = [t.get("name") for t in themes]
    if len(set(names)) != len(names):
        found.append("duplicate theme names")
    if data.get("default") not in names:
        found.append("the default theme is not in the list")
    keys = None
    for t in themes:
        name = t.get("name")
        missing = [f for f in ("name", "label", "scheme", "hue", "accent", "derived", "tokens") if f not in t]
        if missing:
            found.append(f"{name}: no {', '.join(missing)}")
            continue
        if t["scheme"] not in SCHEMES:
            found.append(f"{name}: scheme must be one of {SCHEMES}")
        if t["derived"] != derive(t["hue"], t["accent"]):
            found.append(f"{name}: 'derived' is not what derive({t['hue']}, {t['accent']}) returns")
        for key in t.get("overrides", {}):
            if key not in t["derived"]:
                found.append(f"{name}: override {key} is not a derived token")
        for key in t["tokens"]:
            if key in t["derived"]:
                found.append(f"{name}: {key} is derived; put it in 'overrides'")
        for key, value in theme_tokens(t).items():
            if not key.startswith("--") or not isinstance(value, str) or not value.strip() or ";" in value:
                found.append(f"{name}: bad token {key}: {value!r}")
        own = set(theme_tokens(t))
        if keys is None:
            keys = own
        elif own != keys:
            found.append(f"{name}: token set differs from the first theme: {sorted(own ^ keys)}")
    fonts = data.get("fonts", {})
    for role in ("text", "mono"):
        if not isinstance(fonts.get(role), dict) or not fonts[role].get("stack"):
            found.append(f"fonts.{role}.stack missing")
    if not fonts.get("text", {}).get("file"):
        found.append("fonts.text.file missing")
    return found


# ---------------------------------------------------------------------------------------------------------------------
# Output

def _selectors(theme: dict, default: str, scope: bool) -> list[str]:
    name = theme["name"]
    out = [":root"] if name == default else []
    out.append(f':root[data-theme="{name}"]')
    if scope:
        out.append(f'[data-theme-scope="{name}"]')
    return out


def _rule(theme: dict, default: str, indent: str, scope: bool) -> str:
    lines = [f"/* {theme['label']}: {theme['scheme']}, hue {theme['hue']}, accent {theme['accent']} */",
             ",\n".join(_selectors(theme, default, scope)) + " {",
             f"{indent}color-scheme: {theme['scheme']};"]
    lines += [f"{indent}{key}: {value};" for key, value in theme_tokens(theme).items()]
    lines.append("}")
    return "\n".join(lines)


def kit_css(data: dict) -> str:
    head = (
        "/* GENERATED by build/gen_themes.py from src/premiere_deck/ui/themes.json; do not edit by hand.\n"
        "   The project themes (docs/HOST_UI.md 7): every colour token of each theme. The page sets data-theme on\n"
        "   <html> before the first paint and switches it with js/theme.js applyTheme(); without the attribute the\n"
        "   default theme applies. data-theme-scope=\"<name>\" gives a subtree another theme's tokens (the mini\n"
        "   previews of the theme cards). */\n"
    )
    rules = [_rule(t, data["default"], "  ", True) for t in data["themes"]]
    return head + "\n" + "\n\n".join(rules) + "\n"


def panel_block(data: dict) -> str:
    fonts = data["fonts"]
    text = fonts["text"]
    ind = "    "
    parts = [
        BEGIN_MARK,
        "/* Do not edit by hand: change src/premiere_deck/ui/themes.json, then run build/gen_themes.py (docs/PANEL.md 3). */",
        "",
        "@font-face {",
        f'{ind}font-family: "{text["family"]}";',
        f'{ind}src: url("../fonts/{text["file"]}") format("woff2");',
        f"{ind}font-weight: {text['weight']};",
        f"{ind}font-style: normal;",
        f"{ind}font-display: block;",
        "}",
        "",
        ":root {",
        f"{ind}--font-text: {text['stack']};",
        f"{ind}--font-mono: {fonts['mono']['stack']};",
        "}",
        "",
    ]
    rules = [_rule(t, data["default"], ind, False) for t in data["themes"]]
    return "\n".join(parts) + "\n" + "\n\n".join(rules) + "\n" + END_MARK


def splice(text: str, block: str) -> str:
    """panel.css with its generated block replaced; a file without markers gets the block after its header comment."""
    start = text.find(BEGIN_MARK)
    end = text.find(END_MARK)
    if start >= 0 and end > start:
        return text[:start] + block + text[end + len(END_MARK):]
    if start >= 0 or end >= 0:
        raise SystemExit(f"{PANEL_CSS}: only one of the generated block markers is present")
    head = re.match(r"\s*/\*.*?\*/\n", text, re.S)
    cut = head.end() if head else 0
    return text[:cut] + "\n" + block + "\n" + text[cut:]


def outputs(data: dict) -> dict[Path, str]:
    panel_text = PANEL_CSS.read_text("utf-8")
    return {KIT_THEMES_CSS: kit_css(data), PANEL_CSS: splice(panel_text, panel_block(data))}


