# Contrast (WCAG 2.x): alpha compositing in sRGB as the browser does, then relative luminance.

_COLOR = re.compile(r"#[0-9a-fA-F]{6}\b|rgba?\([^)]*\)")


def parse_color(text: str) -> tuple[float, float, float, float]:
    text = text.strip()
    if text.startswith("#"):
        r, g, b = _rgb(text)
        return (r, g, b, 1.0)
    inner = text[text.index("(") + 1:text.rindex(")")]
    parts = [float(p) for p in inner.replace("/", ",").split(",")]
    return (parts[0], parts[1], parts[2], parts[3] if len(parts) > 3 else 1.0)


def over(top, bottom):
    r, g, b, a = top
    return (r * a + bottom[0] * (1 - a), g * a + bottom[1] * (1 - a), b * a + bottom[2] * (1 - a), 1.0)


def luminance(color) -> float:
    def channel(v: float) -> float:
        v /= 255
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = color[:3]
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def ratio(a, b) -> float:
    x, y = sorted((luminance(a), luminance(b)), reverse=True)
    return (x + 0.05) / (y + 0.05)


def scene_points(tok: dict[str, str]) -> dict[str, tuple]:
    """Scene colours under the glass: the three base stops, the core of the large hue field (alpha 0.44 * 0.9 of
    js/background.js fieldsFor(), scaled by --scene-fields-o) and the floor pool (accent at 0.26 scaled by
    --scene-floor-o), both over the bottom stop."""
    c = lambda k: parse_color(tok[k])  # noqa: E731
    bottom = c("--bg-bottom")
    fields_o = float(tok.get("--scene-fields-o", "1"))
    floor_o = float(tok.get("--scene-floor-o", "1"))
    hue = c("--scene-hue")
    accent = c("--scene-accent")
    return {
        "scene top": c("--bg-top"),
        "scene mid": c("--bg-mid"),
        "scene bottom": bottom,
        "hue field peak": over((*hue[:3], 0.44 * 0.9 * fields_o), bottom),
        "accent floor peak": over((*accent[:3], 0.26 * floor_o), bottom),
    }


def contrast_report(tok: dict[str, str]) -> list[dict]:
    """The worst contrast of each text ink over the glass (--tint-regular) and the sheet (--tint-sheet) above every
    scene point; the label on the accent glass (--hero-ink on every stop of --accent-grad-a); the label of the
    running hero pill (--hero-ink on --hero-track-tint) and of the finished one (--hero-done-ink on
    --hero-done-tint)."""
    c = lambda k: parse_color(tok[k])  # noqa: E731
    points = scene_points(tok)
    surfaces = {}
    for pn, p in points.items():
        surfaces[f"glass over {pn}"] = over(c("--tint-regular"), p)
        surfaces[f"sheet over {pn}"] = over(c("--tint-sheet"), p)
    rows = []
    for ink in TEXT_INKS:
        worst, where = min((ratio(over(c(ink), s), s), sn) for sn, s in surfaces.items())
        rows.append({"ink": ink, "min": round(worst, 2), "worst": where, "pass": worst >= MIN_CONTRAST})
    hero = c("--hero-ink")
    stops = [parse_color(m.group(0)) for m in _COLOR.finditer(tok["--accent-grad-a"])]
    worst = min(ratio(hero, over(g, p)) for p in points.values() for g in stops)
    rows.append({"ink": "--hero-ink on --accent-grad-a", "min": round(worst, 2), "worst": "accent glass",
                 "pass": worst >= MIN_CONTRAST})
    track = c("--hero-track-tint")
    worst = min(ratio(hero, over(track, p)) for p in points.values())
    rows.append({"ink": "--hero-ink on --hero-track-tint", "min": round(worst, 2), "worst": "running hero pill",
                 "pass": worst >= MIN_CONTRAST})
    done = c("--hero-done-ink")
    stops = [parse_color(m.group(0)) for m in _COLOR.finditer(tok["--hero-done-tint"])]
    worst = min(ratio(over(done, over(g, p)), over(g, p)) for p in points.values() for g in stops)
    rows.append({"ink": "--hero-done-ink on --hero-done-tint", "min": round(worst, 2), "worst": "finished hero pill",
                 "pass": worst >= MIN_CONTRAST})
    return rows


# ---------------------------------------------------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render ui/themes.json into the kit's themes.css and panel.css.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when an output is out of date")
    parser.add_argument("--contrast", action="store_true", help="print the contrast table")
    args = parser.parse_args(argv)
    data = load()
    found = problems(data)
    if found:
        for line in found:
            print(f"themes.json: {line}", file=sys.stderr)
        return 2
    if args.contrast:
        for t in data["themes"]:
            print(t["name"])
            for row in contrast_report(theme_tokens(t)):
                print(f"  {'ok  ' if row['pass'] else 'FAIL'} {row['ink']:<34} {row['min']:6.2f}  ({row['worst']})")
    stale = []
    for path, text in outputs(data).items():
        current = path.read_text("utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path)
        else:
            path.write_bytes(text.encode("utf-8"))
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)} (run python build/gen_themes.py)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
